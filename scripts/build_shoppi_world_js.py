"""Write src/secondbrain/static/shoppi_world.js from examples/shoppi/*.csv.

The Graph, HQ, Live Commerce and TimescaleDB pages generate a demo feed in the browser
when the Live Commerce engine isn't running (as on Cloud Run). This file gives those
feeds the real Shoppi merchants and catalogs, so they never invent other platforms.

    uv run python scripts/build_shoppi_world_js.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "examples" / "shoppi"
OUT = ROOT / "src" / "secondbrain" / "static" / "shoppi_world.js"

# Shoppi category -> the demo feeds' category (they know Grocery, Gourmet, Fashion, Home, Beauty, Electronics).
DEMO_CATEGORY = {
    "Namkeen": "Gourmet", "Ready Meals": "Gourmet", "Frozen": "Gourmet", "Sweets": "Gourmet", "Gifting": "Gourmet",
    "Staples": "Grocery", "Beverages": "Grocery", "Dairy": "Grocery", "Fruits & Vegetables": "Grocery",
    "Household": "Home", "Clothing": "Fashion", "Outerwear": "Fashion", "Accessories": "Fashion", "Footwear": "Fashion",
}
# Same relative size as the engine's world (commerce/world.py SHOPPI_SIZE) and lead times.
SIZE = {"haldirams": 6.0, "bigbasket": 9.0, "fabindia": 3.0, "bata": 3.0}
LEAD = {"haldirams": 3, "bigbasket": 2, "fabindia": 14, "bata": 10}


def main() -> None:
    merchants = list(csv.DictReader(open(SRC / "merchants.csv", encoding="utf-8")))
    products = list(csv.DictReader(open(SRC / "products.csv", encoding="utf-8")))
    out = []
    for m in merchants:
        mine = [p for p in products if p["merchant_id"] == m["id"]]
        cats = [DEMO_CATEGORY.get(p["category"], "Home") for p in mine]
        main_cats = sorted(set(cats), key=lambda c: -cats.count(c))
        out.append({
            "id": f"shoppi-{m['slug']}", "slug": m["slug"], "name": m["name"], "city": m["city"],
            "lat": float(m["lat"]), "lng": float(m["lng"]), "size": SIZE.get(m["slug"], 2.0),
            "categories": main_cats,
            "products": [{
                "sku": p["sku"], "name": p["title"], "category": DEMO_CATEGORY.get(p["category"], "Home"),
                "shoppi_category": p["category"], "price": float(p["price"]), "cost": float(p["cost"]),
                "stock": int(p["inventory"]), "lead_days": LEAD.get(m["slug"], 7),
                "perishable": p["category"] in ("Dairy", "Fruits & Vegetables", "Ready Meals"),
                "sold_30d": int(p["units_sold_last_30d"]),
            } for p in mine],
        })
    body = json.dumps({"platform": {"id": "shoppi", "name": "Shoppi", "kind": "Marketplace merchants",
                                    "color": "#E4572E"},
                       "customers": 40000, "merchants": out}, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text("// Generated by scripts/build_shoppi_world_js.py from examples/shoppi. Do not edit.\n"
                   f"window.SHOPPI_WORLD = {body};\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(out)} merchants, {sum(len(m['products']) for m in out)} products")


if __name__ == "__main__":
    main()
